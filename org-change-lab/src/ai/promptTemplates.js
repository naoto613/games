export const AGENTS = Object.keys(TEMPLATES);

export function buildPrompt(agent, input) {
  const template = TEMPLATES[agent];
  if (!template) throw new Error(`不明なエージェントです：${agent}`);
  const schema = SCHEMAS[agent];
  return { system: SYSTEM_PROMPT, user: template(input), schema };
}

// コピー＆ペースト方式用：1つのテキストにまとめる
export function buildManualPrompt(agent, input) {
  const { system, user, schema } = buildPrompt(agent, input);
  return `${system}

---

${user}

---

【出力形式】
次の JSON Schema に従う JSON オブジェクトだけを出力してください。説明文やコードフェンスは不要です。
${JSON.stringify(schema, null, 2)}`;
}
